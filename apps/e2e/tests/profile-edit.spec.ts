import { expect, test } from '@playwright/test';
import { en } from '../../mobile/src/copy/en';
import { button, chip, shown, signedInWithPlan } from '../support/app';

const p = en.home.profile;
const o = en.onboarding.steps;

/** Settings → Your profile → one row, as a signed-in user with a plan. */
async function openRow(page: import('@playwright/test').Page, row: string) {
  await page.goto('/settings');
  await page.getByRole('button', { name: p.link }).first().click();
  await expect(page).toHaveURL(/\/profile$/);
  await expect(shown(page, p.title)).toBeVisible();
  await page.getByRole('button', { name: row }).first().click();
}

test('changing equipment marks the plan outdated; "Update my plan" is the only thing that regenerates it', async ({ page }) => {
  const backend = await signedInWithPlan(page);

  await openRow(page, p.rows.equipment);
  await expect(page).toHaveURL(/\/profile\/equipment/);
  // It is the onboarding step, pre-filled with what is saved: Gym and Full gym are selected.
  await expect(chip(page, o.equipment.equipment.full_gym)).toBeChecked();
  await chip(page, o.equipment.equipment.full_gym).click();
  await chip(page, o.equipment.equipment.dumbbells).click();
  await button(page, p.save).click();

  // The edit went to the own profile row, in the shape onboarding writes.
  await expect.poll(() => backend.writesTo('/profiles').length).toBeGreaterThan(0);
  const saved = backend.writesTo('/profiles').at(-1)!.body as { onboarding: { equipment: string[]; consents: unknown } };
  expect(saved.onboarding.equipment).toEqual(['dumbbells']);
  expect(saved.onboarding.consents).toBeTruthy();

  await expect(page).toHaveURL(/\/profile$/);

  // Nothing regenerated by itself.
  expect(backend.functionCalls).not.toContain('generate-plan');

  // The card shows on Today and on Plan.
  await page.goto('/');
  await expect(shown(page, p.outdatedBody)).toBeVisible();
  await page.goto('/plan');
  await expect(shown(page, p.outdatedBody)).toBeVisible();
  expect(backend.functionCalls).not.toContain('generate-plan');

  await page.getByRole('alert').getByRole('button', { name: p.outdatedCta }).click();
  await expect(page).toHaveURL(/\/update-plan/);
  await expect(shown(page, en.home.update.title)).toBeVisible();
  await expect.poll(() => backend.functionCalls.filter((n) => n === 'generate-plan').length).toBeGreaterThan(0);
});

test('a units-only change does not mark the plan outdated', async ({ page }) => {
  const backend = await signedInWithPlan(page);

  await openRow(page, p.rows.basics);
  await expect(page).toHaveURL(/\/profile\/basics/);
  await chip(page, o.basics.units.imperial).click();
  await button(page, p.save).click();

  await expect.poll(() => backend.writesTo('/profiles').length).toBeGreaterThan(0);
  expect((backend.writesTo('/profiles').at(-1)!.body as { units: string }).units).toBe('imperial');
  await expect(page).toHaveURL(/\/profile$/);

  await page.goto('/');
  await expect(shown(page, en.home.title)).toBeVisible();
  await expect(page.getByText(p.outdatedBody, { exact: true })).toHaveCount(0);
  await page.goto('/plan');
  await expect(shown(page, en.home.planTitle)).toBeVisible();
  await expect(page.getByText(p.outdatedBody, { exact: true })).toHaveCount(0);
});

test('leaving an edit screen without saving changes nothing', async ({ page }) => {
  const backend = await signedInWithPlan(page);

  await openRow(page, p.rows.equipment);
  await chip(page, o.equipment.equipment.dumbbells).click();
  await button(page, en.common.back).click();

  await expect(page).toHaveURL(/\/profile$/);
  expect(backend.writesTo('/profiles')).toHaveLength(0);
  await page.goto('/');
  await expect(page.getByText(p.outdatedBody, { exact: true })).toHaveCount(0);
});
