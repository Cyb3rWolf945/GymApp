import type { PGlite } from '@electric-sql/pglite';

const TS: Record<string, string> = {
  uuid: 'string', text: 'string', date: 'string', 'timestamp with time zone': 'string',
  integer: 'number', numeric: 'number', boolean: 'boolean', jsonb: 'Json',
};

/** Generates a Supabase-style `Database` type from the migrated schema. */
export async function generateTypes(db: PGlite): Promise<string> {
  const cols = (
    await db.query<{ t: string; c: string; dt: string; udt: string; n: string; d: string | null }>(
      `select table_name t, column_name c, data_type dt, udt_name udt, is_nullable n, column_default d
       from information_schema.columns where table_schema='public' order by table_name, ordinal_position`,
    )
  ).rows;
  const enums = (
    await db.query<{ n: string; v: string }>(
      `select t.typname n, e.enumlabel v from pg_enum e join pg_type t on t.oid=e.enumtypid order by t.typname, e.enumsortorder`,
    )
  ).rows;
  const enumNames = new Set(enums.map((e) => e.n));
  const tsType = (c: (typeof cols)[number]) => {
    if (c.dt === 'USER-DEFINED' && enumNames.has(c.udt)) return `Database['public']['Enums']['${c.udt}']`;
    if (c.dt === 'ARRAY' && c.udt === '_text') return 'string[]';
    return TS[c.dt] ?? 'unknown';
  };
  const tables = [...new Set(cols.map((c) => c.t))];
  const out: string[] = [
    '// GENERATED by `pnpm gen:types` from supabase/migrations. Do not edit.',
    'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];',
    '',
    'export type Database = {',
    '  public: {',
    '    Tables: {',
  ];
  for (const t of tables) {
    const tc = cols.filter((c) => c.t === t);
    const row = tc.map((c) => `          ${c.c}: ${tsType(c)}${c.n === 'YES' ? ' | null' : ''};`);
    const ins = tc.map((c) => {
      const opt = c.n === 'YES' || c.d !== null ? '?' : '';
      return `          ${c.c}${opt}: ${tsType(c)}${c.n === 'YES' ? ' | null' : ''};`;
    });
    out.push(`      ${t}: {`, '        Row: {', ...row, '        };', '        Insert: {', ...ins, '        };');
    out.push('        Update: Partial<Database[\'public\'][\'Tables\'][\'' + t + '\'][\'Insert\']>;', '      };');
  }
  out.push('    };', '    Enums: {');
  for (const n of enumNames) {
    out.push(`      ${n}: ${enums.filter((e) => e.n === n).map((e) => `'${e.v}'`).join(' | ')};`);
  }
  out.push('    };', '  };', '};', '');
  out.push(
    "export type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row'];",
    "export type TablesInsert<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Insert'];",
    '',
  );
  return out.join('\n');
}
